type TransferRole = "manager" | "operator"

export type TeamOwnershipTransferInput = {
  teams: Array<{ id: string; name: string; masterId: string; isDefault: boolean; deletedAt: Date | null }>
  profiles: Array<{ id: string; email: string; fullName: string | null; managerId: string | null; isMaster: boolean; deletedAt: Date | null }>
  memberships: Array<{ teamId: string; profileId: string; role: TransferRole }>
}

export type TeamOwnershipTransferItem = {
  action: "transfer" | "already_transferred"
  teamId: string
  teamName: string
  currentMasterId: string
  targetMasterId: string
  targetEmail: string
  shouldBeDefault: boolean
}

export type TeamOwnershipTransferBlockedItem = {
  teamId: string
  teamName: string
  targetMasterId: string
  targetEmail: string
  reason:
    | "team_missing"
    | "team_deleted"
    | "source_owner_mismatch"
    | "target_profile_missing"
    | "target_deleted"
    | "target_email_mismatch"
    | "target_membership_missing"
    | "target_membership_not_manager"
}

export type TeamOwnershipTransferProfileUpdate = {
  profileId: string
  email: string
  defaultTeamId: string
  shouldBecomeMaster: boolean
  shouldClearManager: boolean
}

export type TeamOwnershipTransferPlan = {
  transfers: TeamOwnershipTransferItem[]
  blocked: TeamOwnershipTransferBlockedItem[]
  profileUpdates: TeamOwnershipTransferProfileUpdate[]
}

export function buildTeamOwnershipTransferPlan(input: TeamOwnershipTransferInput): TeamOwnershipTransferPlan {
  const teamsById = new Map(input.teams.map((team) => [team.id, team]))
  const profilesById = new Map(input.profiles.map((profile) => [profile.id, profile]))
  const membershipsByKey = new Map(input.memberships.map((membership) => [`${membership.teamId}:${membership.profileId}`, membership]))
  const firstTeamByTarget = new Map<string, string>()

  for (const target of TEAM_OWNERSHIP_TRANSFER_TARGETS) {
    if (!firstTeamByTarget.has(target.profileId)) firstTeamByTarget.set(target.profileId, target.teamId)
  }

  const transfers: TeamOwnershipTransferItem[] = []
  const blocked: TeamOwnershipTransferBlockedItem[] = []

  for (const target of TEAM_OWNERSHIP_TRANSFER_TARGETS) {
    const team = teamsById.get(target.teamId)
    const profile = profilesById.get(target.profileId)
    const blockedBase = { teamId: target.teamId, teamName: target.teamName, targetMasterId: target.profileId, targetEmail: target.email }

    if (!team) {
      blocked.push({ ...blockedBase, reason: "team_missing" })
      continue
    }
    if (team.deletedAt) {
      blocked.push({ ...blockedBase, reason: "team_deleted" })
      continue
    }
    if (!profile) {
      blocked.push({ ...blockedBase, reason: "target_profile_missing" })
      continue
    }
    if (profile.deletedAt) {
      blocked.push({ ...blockedBase, reason: "target_deleted" })
      continue
    }
    if (profile.email.trim().toLowerCase() !== target.email.trim().toLowerCase()) {
      blocked.push({ ...blockedBase, reason: "target_email_mismatch" })
      continue
    }
    const membership = membershipsByKey.get(`${target.teamId}:${target.profileId}`)
    if (!membership) {
      blocked.push({ ...blockedBase, reason: "target_membership_missing" })
      continue
    }
    if (membership.role !== "manager") {
      blocked.push({ ...blockedBase, reason: "target_membership_not_manager" })
      continue
    }
    if (team.masterId !== BRUNO_PROFILE_ID && team.masterId !== target.profileId) {
      blocked.push({ ...blockedBase, reason: "source_owner_mismatch" })
      continue
    }

    transfers.push({
      action: team.masterId === target.profileId ? "already_transferred" : "transfer",
      teamId: target.teamId,
      teamName: target.teamName,
      currentMasterId: team.masterId,
      targetMasterId: target.profileId,
      targetEmail: target.email,
      shouldBeDefault: firstTeamByTarget.get(target.profileId) === target.teamId,
    })
  }

  const profileUpdates = [...new Set(TEAM_OWNERSHIP_TRANSFER_TARGETS.map((target) => target.profileId))]
    .map((profileId) => profilesById.get(profileId))
    .filter((profile): profile is NonNullable<typeof profile> => Boolean(profile))
    .map((profile) => ({
      profileId: profile.id,
      email: profile.email,
      defaultTeamId: firstTeamByTarget.get(profile.id)!,
      shouldBecomeMaster: !profile.isMaster,
      shouldClearManager: profile.managerId !== null,
    }))

  return { transfers, blocked, profileUpdates }
}
